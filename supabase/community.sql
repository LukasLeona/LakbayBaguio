-- Lakbay Baguio anonymous nearby chat
-- Run this entire file in the Supabase SQL editor, then enable Anonymous Sign-Ins.
-- Exact coordinates are stored only in the protected presence table. The public
-- API returns distance bands plus coordinates rounded to a coarse map cell.

begin;

create extension if not exists pgcrypto;
create schema if not exists extensions;
create extension if not exists postgis with schema extensions;

create table if not exists public.profiles (
  user_id uuid primary key references auth.users(id) on delete cascade,
  alias text not null check (
    alias ~ '^(Cloud|Cozy|Foggy|Gentle|Misty|Pine|Quiet|Sage|Sunny|Wandering)(Deer|Finch|Fox|Hiker|Owl|Panda|Robin|Spruce|Taho|Trail)[0-9]{2}$'
  ),
  avatar_seed integer not null default 0,
  created_at timestamptz not null default now(),
  updated_at timestamptz not null default now()
);

create table if not exists public.presence (
  user_id uuid primary key references public.profiles(user_id) on delete cascade,
  location extensions.geography(point, 4326) not null,
  is_discoverable boolean not null default false,
  last_seen timestamptz not null default now()
);

create index if not exists presence_location_gix on public.presence using gist (location);
create index if not exists presence_active_idx on public.presence (last_seen desc) where is_discoverable;

create table if not exists public.chat_requests (
  id uuid primary key default gen_random_uuid(),
  sender_id uuid not null references public.profiles(user_id) on delete cascade,
  receiver_id uuid not null references public.profiles(user_id) on delete cascade,
  status text not null default 'pending' check (status in ('pending', 'accepted', 'declined')),
  created_at timestamptz not null default now(),
  responded_at timestamptz,
  check (sender_id <> receiver_id)
);

create unique index if not exists one_pending_request_per_pair
  on public.chat_requests (
    least(sender_id::text, receiver_id::text),
    greatest(sender_id::text, receiver_id::text)
  )
  where status = 'pending';

create table if not exists public.conversations (
  id uuid primary key default gen_random_uuid(),
  created_at timestamptz not null default now()
);

create table if not exists public.conversation_members (
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  user_id uuid not null references public.profiles(user_id) on delete cascade,
  joined_at timestamptz not null default now(),
  last_read_at timestamptz not null default now(),
  left_at timestamptz,
  primary key (conversation_id, user_id)
);

alter table public.conversation_members add column if not exists left_at timestamptz;

create index if not exists conversation_members_user_idx on public.conversation_members (user_id, joined_at desc);

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  conversation_id uuid not null references public.conversations(id) on delete cascade,
  sender_id uuid not null default auth.uid() references public.profiles(user_id) on delete cascade,
  body text not null check (char_length(btrim(body)) between 1 and 600),
  created_at timestamptz not null default now()
);

create index if not exists messages_conversation_time_idx on public.messages (conversation_id, created_at);

create table if not exists public.blocks (
  blocker_id uuid not null default auth.uid() references public.profiles(user_id) on delete cascade,
  blocked_id uuid not null references public.profiles(user_id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (blocker_id, blocked_id),
  check (blocker_id <> blocked_id)
);

create table if not exists public.reports (
  id bigint generated by default as identity primary key,
  reporter_id uuid not null default auth.uid() references public.profiles(user_id) on delete cascade,
  reported_id uuid not null references public.profiles(user_id) on delete cascade,
  conversation_id uuid references public.conversations(id) on delete set null,
  reason text not null check (reason in ('harassment', 'spam', 'unsafe', 'other')),
  details text check (details is null or char_length(details) <= 1000),
  created_at timestamptz not null default now(),
  resolved_at timestamptz,
  check (reporter_id <> reported_id)
);

create table if not exists public.restaurant_inquiries (
  id uuid primary key default gen_random_uuid(),
  restaurant_name text not null check (char_length(restaurant_name) between 2 and 100),
  contact_name text not null check (char_length(contact_name) between 2 and 80),
  email text not null check (char_length(email) between 5 and 160),
  phone text check (phone is null or char_length(phone) <= 30),
  address text not null check (char_length(address) between 5 and 240),
  social_url text check (social_url is null or char_length(social_url) <= 300),
  message text not null check (char_length(message) between 20 and 1200),
  status text not null default 'new' check (status in ('new', 'reviewing', 'contacted', 'declined', 'featured')),
  consented_at timestamptz not null,
  created_at timestamptz not null default now(),
  reviewed_at timestamptz
);

create index if not exists restaurant_inquiries_email_created_idx
  on public.restaurant_inquiries (email, created_at desc);

