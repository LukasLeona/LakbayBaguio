drop policy if exists "Users read their own profile" on public.profiles;
create policy "Users read their own profile"
  on public.profiles for select to authenticated using (user_id = auth.uid());

drop policy if exists "Users create their own profile" on public.profiles;
create policy "Users create their own profile"
  on public.profiles for insert to authenticated with check (user_id = auth.uid());

drop policy if exists "Users update their own profile" on public.profiles;
create policy "Users update their own profile"
  on public.profiles for update to authenticated
  using (user_id = auth.uid()) with check (user_id = auth.uid());

drop policy if exists "Participants read their chat requests" on public.chat_requests;
create policy "Participants read their chat requests"
  on public.chat_requests for select to authenticated
  using (sender_id = auth.uid() or receiver_id = auth.uid());

drop policy if exists "Members read conversations" on public.conversations;
create policy "Members read conversations"
  on public.conversations for select to authenticated
  using (public.can_access_conversation(id));

drop policy if exists "Members read conversation membership" on public.conversation_members;
create policy "Members read conversation membership"
  on public.conversation_members for select to authenticated
  using (public.can_access_conversation(conversation_id));

drop policy if exists "Members read messages" on public.messages;
create policy "Members read messages"
  on public.messages for select to authenticated
  using (public.can_access_conversation(conversation_id));

drop policy if exists "Members send their own messages" on public.messages;
create policy "Members send their own messages"
  on public.messages for insert to authenticated
  with check (
    sender_id = auth.uid()
    and public.can_access_conversation(conversation_id)
    and char_length(btrim(body)) between 1 and 600
  );

drop policy if exists "Users read their own blocks" on public.blocks;
create policy "Users read their own blocks"
  on public.blocks for select to authenticated using (blocker_id = auth.uid());

drop policy if exists "Users remove their own blocks" on public.blocks;
create policy "Users remove their own blocks"
  on public.blocks for delete to authenticated using (blocker_id = auth.uid());

drop policy if exists "Users submit their own reports" on public.reports;
create policy "Users submit their own reports"
  on public.reports for insert to authenticated
  with check (
    reporter_id = auth.uid()
    and reported_id <> auth.uid()
    and conversation_id is not null
    and public.can_access_conversation(conversation_id)
  );

create or replace function public.upsert_presence(
  p_latitude double precision,
  p_longitude double precision,
  p_discoverable boolean default true
)
returns void
language plpgsql
security definer
set search_path = public, extensions
as $$
begin
  if auth.uid() is null then
    raise exception 'Authentication required';
  end if;
  if p_latitude not between -90 and 90 or p_longitude not between -180 and 180 then
    raise exception 'Invalid coordinates';
  end if;

  insert into public.presence (user_id, location, is_discoverable, last_seen)
  values (
    auth.uid(),
    st_setsrid(st_makepoint(p_longitude, p_latitude), 4326)::geography,
    p_discoverable,
    now()
  )
  on conflict (user_id) do update set
    location = excluded.location,
    is_discoverable = excluded.is_discoverable,
    last_seen = now();
end;
$$;

create or replace function public.set_presence_offline()
returns void
language sql
security definer
set search_path = public
as $$
  delete from public.presence where user_id = auth.uid();
$$;

