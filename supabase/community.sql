create or replace function public.nearby_profiles(p_radius_meters integer default 5000)
returns table (
  user_id uuid,
  alias text,
  avatar_seed integer,
  distance_band text,
  display_latitude double precision,
  display_longitude double precision,
  last_seen timestamptz
)
language sql
stable
security definer
set search_path = public, extensions
as $$
  with origin as (
    select location as point
    from public.presence
    where user_id = auth.uid()
      and is_discoverable
      and last_seen > now() - interval '2 minutes'
  ), candidates as (
    select
      p.user_id,
      p.alias,
      p.avatar_seed,
      pr.last_seen,
      pr.location,
      st_distance(pr.location, origin.point) as distance_meters
    from public.presence pr
    join public.profiles p on p.user_id = pr.user_id
    cross join origin
    where auth.uid() is not null
      and pr.user_id <> auth.uid()
      and pr.is_discoverable
      and pr.last_seen > now() - interval '2 minutes'
      and st_dwithin(pr.location, origin.point, least(greatest(coalesce(p_radius_meters, 5000), 500), 5000))
      and not exists (
        select 1 from public.blocks b
        where (b.blocker_id = auth.uid() and b.blocked_id = pr.user_id)
           or (b.blocker_id = pr.user_id and b.blocked_id = auth.uid())
      )
  )
  select
    candidates.user_id,
    candidates.alias,
    candidates.avatar_seed,
    case
      when distance_meters < 500 then 'Less than 500 m'
      when distance_meters < 1500 then '0.5–1.5 km'
      when distance_meters < 3000 then '1.5–3 km'
      else '3–5 km'
    end as distance_band,
    round(st_y(candidates.location::geometry)::numeric, 2)::double precision as display_latitude,
    round(st_x(candidates.location::geometry)::numeric, 2)::double precision as display_longitude,
    candidates.last_seen
  from candidates
  order by distance_meters
  limit 30;
$$;

create or replace function public.request_chat(p_target_user_id uuid)
returns uuid
language plpgsql
security definer
set search_path = public, extensions
as $$
declare
  v_request_id uuid;
begin
  if auth.uid() is null or p_target_user_id = auth.uid() then
    raise exception 'Invalid chat request';
  end if;
  if not exists (
    select 1
    from public.presence mine
    join public.presence target on target.user_id = p_target_user_id
    where mine.user_id = auth.uid()
      and mine.is_discoverable
      and target.is_discoverable
      and mine.last_seen > now() - interval '2 minutes'
      and target.last_seen > now() - interval '2 minutes'
      and st_dwithin(mine.location, target.location, 5000)
  ) then
    raise exception 'That traveler is no longer available';
  end if;
  if exists (
    select 1 from public.blocks
    where (blocker_id = auth.uid() and blocked_id = p_target_user_id)
       or (blocker_id = p_target_user_id and blocked_id = auth.uid())
  ) then
    raise exception 'Chat is unavailable';
  end if;
  if (
    select count(*)
    from public.chat_requests
    where sender_id = auth.uid() and created_at > now() - interval '1 hour'
  ) >= 12 then
    raise exception 'Too many chat requests. Please try again later';
  end if;

  update public.chat_requests
  set status = 'declined', responded_at = now()
  where status = 'pending'
    and created_at <= now() - interval '24 hours'
    and ((sender_id = auth.uid() and receiver_id = p_target_user_id)
      or (sender_id = p_target_user_id and receiver_id = auth.uid()));
  if exists (
    select 1
    from public.conversation_members mine
    join public.conversation_members theirs using (conversation_id)
    where mine.user_id = auth.uid() and theirs.user_id = p_target_user_id
      and mine.left_at is null and theirs.left_at is null
  ) then
    raise exception 'You already have a conversation with this traveler';
  end if;

  select id into v_request_id
  from public.chat_requests
  where status = 'pending'
    and ((sender_id = auth.uid() and receiver_id = p_target_user_id)
      or (sender_id = p_target_user_id and receiver_id = auth.uid()))
  limit 1;

  if v_request_id is not null then return v_request_id; end if;

  insert into public.chat_requests (sender_id, receiver_id)
  values (auth.uid(), p_target_user_id)
  returning id into v_request_id;
  return v_request_id;
end;
$$;

create or replace function public.list_chat_requests()
returns table (
  request_id uuid,
  sender_id uuid,
  sender_alias text,
  avatar_seed integer,
  created_at timestamptz
)
language sql
stable
security definer
set search_path = public
as $$
  select r.id, r.sender_id, p.alias, p.avatar_seed, r.created_at
  from public.chat_requests r
  join public.profiles p on p.user_id = r.sender_id
  where r.receiver_id = auth.uid()
    and r.status = 'pending'
    and r.created_at > now() - interval '24 hours'
    and not exists (
      select 1 from public.blocks b
      where (b.blocker_id = auth.uid() and b.blocked_id = r.sender_id)
         or (b.blocker_id = r.sender_id and b.blocked_id = auth.uid())
    )
  order by r.created_at desc;
$$;

create or replace function public.respond_to_chat_request(p_request_id uuid, p_accept boolean)
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  v_request public.chat_requests%rowtype;
  v_conversation_id uuid;
begin
  select * into v_request
  from public.chat_requests
  where id = p_request_id and receiver_id = auth.uid() and status = 'pending'
  for update;

  if not found then raise exception 'Chat request is no longer available'; end if;

  if not p_accept then
    update public.chat_requests set status = 'declined', responded_at = now() where id = p_request_id;
    return null;
  end if;

  if exists (
    select 1 from public.blocks
    where (blocker_id = auth.uid() and blocked_id = v_request.sender_id)
       or (blocker_id = v_request.sender_id and blocked_id = auth.uid())
  ) then
    raise exception 'Chat is unavailable';
  end if;

  select mine.conversation_id into v_conversation_id
  from public.conversation_members mine
  join public.conversation_members theirs using (conversation_id)
  where mine.user_id = auth.uid() and theirs.user_id = v_request.sender_id
    and mine.left_at is null and theirs.left_at is null
  limit 1;

  if v_conversation_id is null then
    insert into public.conversations default values returning id into v_conversation_id;
    insert into public.conversation_members (conversation_id, user_id)
    values (v_conversation_id, auth.uid()), (v_conversation_id, v_request.sender_id);
  end if;

  update public.chat_requests set status = 'accepted', responded_at = now() where id = p_request_id;
  return v_conversation_id;
end;
$$;

create or replace function public.list_conversations()
returns table (
  conversation_id uuid,
  partner_id uuid,
  partner_alias text,
  avatar_seed integer,
  distance_band text,
  last_message text,
  last_message_at timestamptz,
  unread_count bigint
)
language sql
stable
security definer
set search_path = public, extensions
as $$
  select
    c.id,
    partner.user_id,
    partner_profile.alias,
    partner_profile.avatar_seed,
    case
      when partner_presence.last_seen is null or partner_presence.last_seen <= now() - interval '2 minutes' then 'Offline'
      else 'Active now'
    end,
    last_message.body,
    last_message.created_at,
    (
      select count(*)
      from public.messages unread
      where unread.conversation_id = c.id
        and unread.sender_id <> auth.uid()
        and unread.created_at > mine.last_read_at
    )
  from public.conversation_members mine
  join public.conversations c on c.id = mine.conversation_id
  join public.conversation_members partner
    on partner.conversation_id = c.id and partner.user_id <> auth.uid()
  join public.profiles partner_profile on partner_profile.user_id = partner.user_id
  left join public.presence partner_presence on partner_presence.user_id = partner.user_id
  left join lateral (
    select m.body, m.created_at
    from public.messages m
    where m.conversation_id = c.id
    order by m.created_at desc
    limit 1
  ) last_message on true
  where mine.user_id = auth.uid()
    and public.can_access_conversation(c.id)
    and not exists (
      select 1 from public.blocks b
      where (b.blocker_id = auth.uid() and b.blocked_id = partner.user_id)
         or (b.blocker_id = partner.user_id and b.blocked_id = auth.uid())
    )
  order by coalesce(last_message.created_at, c.created_at) desc;
$$;

create or replace function public.mark_conversation_read(p_conversation_id uuid)
returns void
language sql
security definer
set search_path = public
as $$
  update public.conversation_members
  set last_read_at = now()
  where conversation_id = p_conversation_id
    and user_id = auth.uid()
    and public.can_access_conversation(p_conversation_id);
$$;

create or replace function public.block_user(p_user_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if auth.uid() is null or p_user_id = auth.uid() then
    raise exception 'Invalid block target';
  end if;

  insert into public.blocks (blocker_id, blocked_id)
  values (auth.uid(), p_user_id)
  on conflict do nothing;

  update public.chat_requests
  set status = 'declined', responded_at = now()
  where status = 'pending'
    and ((sender_id = auth.uid() and receiver_id = p_user_id)
      or (sender_id = p_user_id and receiver_id = auth.uid()));
end;
$$;

create or replace function public.end_conversation(p_conversation_id uuid)
returns void
language plpgsql
security definer
set search_path = public
as $$
begin
  if not public.can_access_conversation(p_conversation_id) then
    raise exception 'Conversation is unavailable';
  end if;

  update public.conversation_members
  set left_at = now()
  where conversation_id = p_conversation_id and left_at is null;
end;
$$;

create or replace function public.cleanup_stale_presence()
returns integer
language plpgsql
security definer
set search_path = public
as $$
declare
  deleted_count integer;
begin
  delete from public.presence where last_seen < now() - interval '24 hours';
  get diagnostics deleted_count = row_count;
  return deleted_count;
end;
$$;

create or replace function public.enforce_message_rate_limit()
returns trigger
language plpgsql
security definer
set search_path = public
as $$
begin
  if (
    select count(*)
    from public.messages
    where sender_id = auth.uid()
      and created_at > now() - interval '1 minute'
  ) >= 15 then
    raise exception 'Message rate limit reached. Please wait a moment';
  end if;
  return new;
end;
$$;

